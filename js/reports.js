function cardExpiration(value){
 if(!/^\d{4}-\d{2}-\d{2}$/.test(value||''))return '';
 const [year,month,day]=value.split('-').map(Number);
 if(month<1||month>12||day<1||day>new Date(Date.UTC(year,month,0)).getUTCDate())return '';
 return new Date(Date.UTC(year+1,month,0)).toLocaleDateString('en-US',{month:'short',day:'2-digit',year:'numeric',timeZone:'UTC'});
}
function qualifiedFor629(p){return ['Qualified','Expert','Pass'].includes(overallStatus(p))}
function cardReadiness(p){
 const missing=[];
 if(!p.name?.trim())missing.push('name');
 if(!p.grade?.trim())missing.push('grade');
 if(!p.organization?.trim())missing.push('organization');
 if(!current()?.authenticatingOfficial?.trim())missing.push('authenticating official');
 if(!cardExpiration(current()?.date))missing.push('class date');
 return missing;
}
